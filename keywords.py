"""재개발 감시용 공용 키워드 세트.

게시판 15곳에 같은 키워드 목록을 복사해 두면(과거 boards.txt 방식) 한 곳만
빠뜨려도 그 구의 공고를 놓치게 된다. 그래서 표준 세트를 코드에 한 번만 정의하고
boards.txt에서는 `@표준` 같은 프리셋 이름으로 참조한다.

키워드 문법 (check_once.keyword_in_title이 해석):
- `모아타운`      : 제목에 그 말이 있으면 통과 (공백은 무시하고 비교)
- `건축허가+제한` : `+`로 이은 말이 **모두** 있으면 통과. "건축허가 등 제한 요청"처럼
                    사이에 다른 말이 끼는 공문 제목을 잡으면서, 단순 "건축허가 신청"
                    같은 일반 건축 민원은 걸러낸다.
"""

# 도시정비 문서에서만 쓰이는 표현 위주의 표준 세트.
# (2026-07-28 감사: '후니동산' 7월 4주차 클리핑 근거 문서 27종 대상 검증)
REDEV_STANDARD = [
    # 사업 유형
    "재개발", "재건축", "신속통합", "신통", "모아타운", "모아주택",
    "도심복합", "도심공공", "소규모주택정비", "가로주택", "재정비촉진",
    "역세권", "휴먼타운",
    # 계획·구역 지정
    "정비계획", "정비구역", "정비사업", "지구단위계획", "관리계획+수립",
    "관리계획+결정", "권리산정", "토지거래허가",
    # 후보지·대상지 선정 단계 (초기 재개발의 핵심 신호)
    "후보지", "대상지+선정", "주민제안", "전문가+자문", "자문회의+결과",
    # 주민 동의·의견 절차
    "동의서", "번호부여", "연번부여", "주민공람", "주민설명회", "주민간담회",
    # 인가 단계
    "조합설립", "사업시행", "관리처분",
    # 투기 방지 조치 (모아타운·신통 추진구역에서 나오는 강한 신호)
    "건축허가+제한",
]

# 넓은 '정비' 키워드까지 쓰는 게시판용 (구청 통합 고시공고 등).
# '정비'는 유지보수·단속 업무에도 쓰여 오탐이 있으므로 check_once의
# UNRELATED_MAINTENANCE_WORDS 가드가 함께 동작한다.
REDEV_WITH_BROAD = REDEV_STANDARD + ["정비"]

# 서울도시공간포털 결정고시 등 도시계획 고시 전용 (사업 유형 + 도시계획 용어)
REDEV_URBAN_NOTICE = REDEV_STANDARD + [
    "도시개발", "도시관리계획", "주택재개발", "주택재건축",
]

PRESETS = {
    "@표준": REDEV_STANDARD,
    "@정비": REDEV_WITH_BROAD,
    "@도시계획": REDEV_URBAN_NOTICE,
}

# 동의 절차가 예고가 아니라 실제로 시작됐다는 신호. 설명회·공람은 아직 예고
# 단계지만, 번호부여(연번부여)·동의서는 주민이 동의서를 접수하기 시작했다는
# 뜻이라 알림에서 빨간 표시로 구분한다(check_boards.py 참고).
URGENT = ["번호부여", "연번부여", "동의서"]


def resolve(tokens):
    """boards.txt에서 읽은 키워드 목록의 `@프리셋`을 실제 키워드로 펼친다.

    프리셋과 개별 키워드를 섞어 쓸 수 있다 (예: `@표준,도시개발`).
    알 수 없는 `@이름`은 그대로 남겨 두지 않고 무시한다(오타로 전체 알림이
    되는 것보다 로그로 드러나는 편이 안전).
    """
    resolved = []
    unknown = []
    for token in tokens:
        token = token.strip()
        if not token:
            continue
        if token.startswith("@"):
            preset = PRESETS.get(token)
            if preset is None:
                unknown.append(token)
                continue
            resolved.extend(preset)
        else:
            resolved.append(token)
    return list(dict.fromkeys(resolved)), unknown
